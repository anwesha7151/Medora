/**
 * The Medora AI pipeline.
 *
 *   user input
 *     → intent detection
 *     → structured extraction
 *     → provider selection
 *     → retrieval
 *     → safety validation
 *     → response + provenance
 *     → feedback (collected in the UI, attached by envelope id)
 *
 * Every stage is recorded in `envelope.trace` so the interface can show what
 * actually happened instead of implying a black box.
 */
import { detectIntent, intentLabels, type IntentResult } from "./intent";
import type {
  PatientSummaryRequest,
  ProviderOutput,
  TriageRequest,
} from "./provider-types";
import { resolveProvider, capabilityLabels } from "./registry";
import { BLOCKED_COPY, detectRedFlags, validate } from "./safety";
import type {
  AiCapability,
  AiConfidence,
  AiEnvelope,
  AiPayload,
  AiSource,
  PipelineStage,
} from "./schemas";

const uid = () => `ai_${Math.random().toString(36).slice(2, 10)}`;

const confidenceFrom = (
  matchScore: number,
  intentScore: number,
  rationale: string,
): AiConfidence => {
  const score = Number((matchScore * 0.7 + intentScore * 0.3).toFixed(2));
  const level: AiConfidence["level"] =
    score >= 0.8
      ? "high"
      : score >= 0.6
        ? "moderate"
        : score >= 0.35
          ? "low"
          : "unverified";
  return { level, score, rationale };
};

interface Timer {
  stages: PipelineStage[];
  mark: (
    name: PipelineStage["name"],
    label: string,
    status: PipelineStage["status"],
    detail: string,
  ) => void;
}

const timer = (): Timer => {
  let last = Date.now();
  const stages: PipelineStage[] = [];
  return {
    stages,
    mark: (name, label, status, detail) => {
      const now = Date.now();
      stages.push({ name, label, status, detail, ms: now - last });
      last = now;
    },
  };
};

const EMERGENCY_SOURCE: AiSource = {
  id: "policy:red-flag-routing",
  label: "Medora red-flag routing",
  detail:
    "A fixed emergency term list. The wording below is written by Medora, never generated by a model.",
  kind: "policy",
  verified: true,
};

function escalationEnvelope(
  capability: AiCapability,
  redFlags: string[],
  trace: PipelineStage[],
): AiEnvelope {
  const payload: AiPayload = {
    kind: "escalation",
    headline: "This needs urgent professional care",
    body: `Your message mentions ${redFlags.join(", ")}. Medora cannot assess emergencies and will not try. Contact your local emergency number or go to the nearest emergency department now.`,
    triggeredBy: redFlags,
    action:
      "Call emergency services. Do not wait for an answer from this assistant.",
  };
  return {
    id: uid(),
    capability,
    createdAt: new Date().toISOString(),
    providerId: "medora-policy",
    providerLabel: "Medora safety policy",
    mode: "demo",
    simulated: false,
    payload,
    confidence: {
      level: "high",
      score: 0.99,
      rationale: "Deterministic red-flag rule; no model involved.",
    },
    sources: [EMERGENCY_SOURCE],
    safety: {
      passed: true,
      rulesRun: ["Red-flag term routing"],
      violations: [],
      redFlags,
      escalate: true,
      notice: "Routed to emergency guidance before any content was generated.",
    },
    followUps: [],
    trace,
  };
}

function wrap<T extends AiPayload>(
  capability: AiCapability,
  provider: { id: string; label: string; mode: "demo" | "live" },
  output: ProviderOutput<T>,
  intent: { confidence: number },
  userText: string,
  trace: PipelineStage[],
): AiEnvelope {
  const safety = validate({
    payload: output.payload,
    sources: output.sources,
    userText,
  });
  const blocked = !safety.passed;

  const payload: AiPayload = blocked
    ? {
        kind: "unavailable",
        headline: BLOCKED_COPY.headline,
        body: `${BLOCKED_COPY.body} Failed checks: ${safety.violations.join(" ")}`,
        missingCapability: capability,
        whatALiveProviderWouldDo:
          "A connected provider must pass the same validator before its output is shown.",
      }
    : output.payload;

  return {
    id: uid(),
    capability,
    createdAt: new Date().toISOString(),
    providerId: provider.id,
    providerLabel: provider.label,
    mode: provider.mode,
    simulated: provider.mode === "demo",
    payload,
    confidence: blocked
      ? {
          level: "unverified",
          score: 0,
          rationale: "Response blocked by the safety validator.",
        }
      : confidenceFrom(
          output.matchScore,
          intent.confidence,
          output.matchRationale,
        ),
    sources: output.sources,
    safety,
    followUps: blocked ? [] : (output.followUps ?? []),
    trace,
  };
}

function unavailable(
  capability: AiCapability,
  headline: string,
  body: string,
  whatALiveProviderWouldDo: string,
  trace: PipelineStage[],
): AiEnvelope {
  return {
    id: uid(),
    capability,
    createdAt: new Date().toISOString(),
    providerId: "medora-demo",
    providerLabel: "Medora demo adapter",
    mode: "demo",
    simulated: true,
    payload: {
      kind: "unavailable",
      headline,
      body,
      missingCapability: capability,
      whatALiveProviderWouldDo,
    },
    confidence: {
      level: "unverified",
      score: 0,
      rationale: "No connected provider could serve this request.",
    },
    sources: [
      {
        id: `policy:unavailable:${capability}`,
        label: "Integration not connected",
        detail: whatALiveProviderWouldDo,
        kind: "policy",
        verified: true,
      },
    ],
    safety: {
      passed: true,
      rulesRun: ["Refuse rather than generate"],
      violations: [],
      redFlags: [],
      escalate: false,
      notice: "Nothing was generated, so nothing needed validating.",
    },
    followUps: [],
    trace,
  };
}

