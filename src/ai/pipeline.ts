/** Free-text assistant entry point: runs the full pipeline. */
export async function runAssistantPipeline(
  question: string,
): Promise<AiEnvelope> {
  const t = timer();

  const redFlags = detectRedFlags(question);
  const intent: IntentResult = detectIntent(question);
  t.mark(
    "intent_detection",
    "Intent detection",
    "ok",
    `${intentLabels[intent.intent]} (${Math.round(intent.confidence * 100)}%)${
      intent.matchedSignals.length ? ` · ${intent.matchedSignals[0]}` : ""
    }`,
  );

  const e = intent.entities;
  t.mark(
    "entity_extraction",
    "Structured extraction",
    "ok",
    [
      e.medicineNames.length
        ? `medicines: ${e.medicineNames.join(", ")}`
        : null,
      e.strength ? `strength: ${e.strength}` : null,
      e.form ? `form: ${e.form}` : null,
      e.symptoms.length ? `symptoms: ${e.symptoms.join(", ")}` : null,
    ]
      .filter(Boolean)
      .join(" · ") || "No structured entities found in the message.",
  );

  if (redFlags.length) {
    t.mark(
      "provider_selection",
      "Provider selection",
      "skipped",
      "Emergency routing bypasses all providers.",
    );
    t.mark(
      "retrieval",
      "Retrieval",
      "skipped",
      "No retrieval is performed for red-flag messages.",
    );
    t.mark(
      "safety_validation",
      "Safety validation",
      "ok",
      `Red flags matched: ${redFlags.join(", ")}`,
    );
    t.mark(
      "response_composition",
      "Response",
      "ok",
      "Fixed emergency copy returned.",
    );
    return escalationEnvelope(intent.capability, redFlags, t.stages);
  }

  const provider = resolveProvider(intent.capability);
  t.mark(
    "provider_selection",
    "Provider selection",
    "ok",
    `${provider.label} · ${provider.mode === "live" ? "live provider" : "demo adapter (simulated)"} for ${capabilityLabels[intent.capability]}`,
  );

  if (intent.intent === "price_or_stock") {
    t.mark(
      "retrieval",
      "Retrieval",
      "blocked",
      "Prices and stock are never answered by the AI layer.",
    );
    t.mark(
      "safety_validation",
      "Safety validation",
      "ok",
      "Refusal path — nothing generated.",
    );
    t.mark(
      "response_composition",
      "Response",
      "ok",
      "Directed to the verified price comparison screens.",
    );
    return unavailable(
      "medicine_intelligence",
      "Prices and stock don't come from the assistant",
      "Medora's assistant is not allowed to state a price or say whether a pharmacy has stock. Those numbers only ever come from the verified pharmacy price feed shown on the comparison and pharmacy screens, with the pharmacy and update time attached.",
      "A connected pharmacy price feed publishes prices and availability with a timestamp per listing.",
      t.stages,
    );
  }

  let output: ProviderOutput<AiPayload> | null = null;

  if (intent.intent === "medicine_explanation") {
    output = (await provider.explainMedicine(
      question,
    )) as ProviderOutput<AiPayload> | null;
  } else if (intent.intent === "medicine_comparison") {
    const stopWords = new Set([
      "compare",
      "vs",
      "versus",
      "and",
      "between",
      "difference",
      "differences",
      "which",
      "better",
      "is",
      "the",
      "what",
      "how",
      "does",
      "differ",
      "from",
    ]);
    const rawTokens = question
      .replace(/[^\w\s]/g, " ")
      .split(/\s+/)
      .filter((w) => w.length > 2 && !stopWords.has(w.toLowerCase()));
    const comparisonList =
      e.medicineIds.length > 0
        ? e.medicineIds
        : e.medicineNames.length > 0
          ? e.medicineNames
          : rawTokens;
    output = (await provider.compareMedicines(
      comparisonList.length >= 1
        ? comparisonList
        : ["paracetamol", "ibuprofen"],
    )) as ProviderOutput<AiPayload> | null;
  } else if (
    intent.intent === "interaction_check" ||
    intent.intent === "allergy_check"
  ) {
    const medList =
      e.medicineNames.length > 0
        ? e.medicineNames
        : question
            .replace(/[^\w\s]/g, " ")
            .split(/\s+/)
            .filter((w) => w.length > 3);
    output = (await provider.checkInteractions(
      medList,
      [],
    )) as ProviderOutput<AiPayload>;
  } else if (intent.intent === "symptom_triage") {
    output = (await provider.triage({
      symptoms: e.symptoms.length > 0 ? e.symptoms : [question],
      freeText: question,
      durationDays: e.durationDays ?? 3,
      severity: 4,
      currentMedicines: [],
      allergies: [],
      selectedRedFlags: [],
    })) as ProviderOutput<AiPayload>;
  } else if (intent.intent === "lab_explanation") {
    output = (await provider.explainLabReport(
      question,
    )) as ProviderOutput<AiPayload> | null;
  } else if (intent.intent === "medicine_search") {
    output = (await provider.interpretSearch(
      question,
    )) as ProviderOutput<AiPayload>;
  }

  if (!output) {
    output = (await provider.answerInformational(
      question,
    )) as ProviderOutput<AiPayload>;
    t.mark(
      "retrieval",
      "Retrieval",
      "ok",
      "No specific record matched; fell back to the honest no-answer path.",
    );
  } else {
    t.mark("retrieval", "Retrieval", "ok", output.matchRationale);
  }

  const envelope = wrap(
    intent.capability,
    provider,
    output,
    intent,
    question,
    t.stages,
  );
  t.mark(
    "safety_validation",
    "Safety validation",
    envelope.safety.passed ? "ok" : "blocked",
    envelope.safety.passed
      ? envelope.safety.notice
      : envelope.safety.violations.join(" "),
  );
  t.mark(
    "response_composition",
    "Response & provenance",
    "ok",
    `${envelope.sources.length} source chip(s) attached · confidence ${envelope.confidence.level}`,
  );
  return { ...envelope, trace: t.stages };
}

/* Direct capability entry points used by the non-chat screens. */

export async function runTriagePipeline(
  request: TriageRequest,
): Promise<AiEnvelope> {
  const t = timer();
  const provider = resolveProvider("symptom_triage");
  t.mark(
    "intent_detection",
    "Intent detection",
    "skipped",
    "Structured triage form — intent is known.",
  );
  t.mark(
    "entity_extraction",
    "Structured extraction",
    "ok",
    `${request.symptoms.length} symptom(s), severity ${request.severity}/10.`,
  );
  t.mark(
    "provider_selection",
    "Provider selection",
    "ok",
    `${provider.label} · ${provider.mode}`,
  );
  const output = await provider.triage(request);
  t.mark("retrieval", "Retrieval", "ok", output.matchRationale);
  const envelope = wrap(
    "symptom_triage",
    provider,
    output,
    { confidence: 0.9 },
    request.freeText,
    t.stages,
  );
  t.mark(
    "safety_validation",
    "Safety validation",
    envelope.safety.passed ? "ok" : "blocked",
    envelope.safety.notice,
  );
  t.mark(
    "response_composition",
    "Response & provenance",
    "ok",
    `${envelope.sources.length} source chip(s) attached.`,
  );
  return { ...envelope, trace: t.stages };
}

