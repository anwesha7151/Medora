/**
 * Patient Longitudinal Health Metrics & Vitals Telemetry Dataset
 * Grounded in Indian clinical benchmarks (ICMR, RSSDI, CSI, CDSCO guidelines).
 */

export interface VitalRecord {
  date: string; // "YYYY-MM-DD" or "DD MMM"
  timestamp: string; // ISO
  systolic: number; // mmHg
  diastolic: number; // mmHg
  pulse: number; // bpm
  fastingGlucose: number; // mg/dL
  ppGlucose: number; // mg/dL (post-prandial)
  weight: number; // kg
  bmi: number; // kg/m2
  spo2: number; // %
  egfr: number; // mL/min/1.73m2
  creatinine: number; // mg/dL
  steps: number;
  adherenceRate: number; // %
  clinicalNote?: string;
}

export interface PatientVitalsSummary {
  patientId: string;
  patientName: string;
  age: number;
  gender: "Male" | "Female" | "Other";
  uhid: string; // Unique Health ID / ABHA
  primaryDiagnosis: string;
  coMorbidities: string[];
  allergies: string[];
  currentMedications: string[];
  treatingDoctor: string;
  lastUpdated: string;
  summaryStats: {
    bloodPressure: {
      latest: string; // "126/82"
      meanSystolic: number;
      meanDiastolic: number;
      status: "Optimal" | "Normal" | "Elevated" | "Stage 1 HTN" | "Stage 2 HTN";
      statusTone: "positive" | "info" | "warning" | "destructive";
      trend: string; // "-4 mmHg vs baseline"
    };
    glucose: {
      latestFasting: number;
      latestPP: number;
      estimatedHbA1c: number;
      timeInRange: number; // %
      status: "Well Controlled" | "Moderate" | "Suboptimal" | "Critical";
      statusTone: "positive" | "info" | "warning" | "destructive";
      trend: string; // "-0.4% HbA1c projected"
    };
    cardiac: {
      restingHR: number;
      hrv: number; // ms
      targetZoneCompliance: number; // %
      status: "Normal Sinus" | "Elevated" | "Bradycardia";
      statusTone: "positive" | "info" | "warning";
      trend: string; // "Stable"
    };
    weightAndBmi: {
      currentWeight: number;
      currentBmi: number;
      weightDelta90d: number; // kg
      bmiCategory: "Underweight" | "Normal" | "Overweight" | "Obese Class 1";
      targetWeight: number;
      statusTone: "positive" | "info" | "warning";
    };
    renal: {
      egfr: number;
      creatinine: number;
      stage: "Stage 1 (Normal)" | "Stage 2 (Mild)" | "Stage 3a (Mild-Mod)";
      statusTone: "positive" | "info" | "warning";
    };
    oxygenation: {
      spo2: number;
      status: "Normal Room Air" | "Borderline" | "Hypoxemia";
      statusTone: "positive" | "warning" | "destructive";
    };
  };
  vitalsHistory: VitalRecord[];
  lipidProfile: {
    metric: string;
    value: number;
    target: number;
    unit: string;
    status: "Optimal" | "Borderline" | "High";
  }[];
  clinicalAlerts: {
    id: string;
    date: string;
    severity: "low" | "medium" | "high";
    title: string;
    detail: string;
    suggestedAction: string;
  }[];
}

